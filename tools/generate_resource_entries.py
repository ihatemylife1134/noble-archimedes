"""Expose indirect resource callbacks grouped into another generated function."""
from pathlib import Path

def generate_resource_entries(generated_dir):
    root = Path(generated_dir)
    source = root / "sub_007A7080_0x7a7080.cpp"
    if not source.exists():
        return None
    content = source.read_text(encoding="utf-8")
    content = content.replace("void sub_007A7080_0x7a7080(", "inline void noble_resource_entries(", 1)
    for address in (0x7A7098, 0x7A7328, 0x7A7358):
        anchor = f"    // 0x{address:x}:"
        if content.count(anchor) != 1:
            raise ValueError(f"Missing resource entry instruction {address:#x}")
        content = content.replace(anchor, f"label_{address:x}:\n" + anchor, 1)
        content = content.replace("        default: break;", f"        case 0x{address:x}u: goto label_{address:x};\n        default: break;", 1)
    for filename, function, address in (
        ("sub_0079C890_0x79c890.cpp", "noble_resource_texture_entries", 0x79C930),
        ("sub_0079C958_0x79c958.cpp", "noble_resource_mesh_entries", 0x79C960),
        ("sub_0079C9B0_0x79c9b0.cpp", "noble_resource_material_entries", 0x79C9F8),
        ("sub_0079CAE8_0x79cae8.cpp", "noble_resource_record_release_entries", 0x79CB28),
        ("sub_00924820_0x924820.cpp", "noble_resource_animation_entries", 0x924828),
        ("sub_00794898_0x794898.cpp", "noble_resource_animation_update_entries", 0x794EA0),
        ("sub_00487B18_0x487b18.cpp", "noble_resource_resolve_entries", 0x487B68),
        ("sub_00471D58_0x471d58.cpp", "noble_scene_object_entries", 0x471DB8),
    ):
        texture = root / filename
        if not texture.exists():
            continue
        extra = texture.read_text(encoding="utf-8")
        original = filename.removesuffix(".cpp")
        extra = extra.replace(f"void {original}(", f"inline void {function}(", 1)
        anchor = f"    // 0x{address:x}:"
        if extra.count(anchor) != 1:
            raise ValueError(f"Missing resource entry {address:#x}")
        if "    switch (ctx->pc) {" not in extra:
            start_pc = int(original.split("_")[1], 16)
            entry = f"    ctx->pc = 0x{start_pc:x}u;"
            if extra.count(entry) < 1:
                raise ValueError(f"Missing generated function entry {start_pc:#x}")
            extra = extra.replace(entry, "    switch (ctx->pc) {\n        default: break;\n    }\n\n" + entry, 1)
        extra = extra.replace(anchor, f"label_{address:x}:\n" + anchor, 1)
        extra = extra.replace("        default: break;", f"        case 0x{address:x}u: goto label_{address:x};\n        default: break;", 1)
        content += "\n" + extra
    output = root / "resource_entry_aliases.hpp"
    content = "#pragma once\n// Generated by tools/generate_resource_entries.py\n" + content
    if not output.exists() or output.read_text(encoding="utf-8") != content:
        output.write_text(content, encoding="utf-8")
    return output

if __name__ == "__main__":
    print(generate_resource_entries("src/recomp/generated"))
