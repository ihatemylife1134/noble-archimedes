"""Generate Hector: skinned mesh, skeleton, 12 animations, FBX exports and previews.
Run:  blender.exe -b -P generate_hector.py -- <out_dir>
Private-use fan rebuild. All geometry/animation is generated by these scripts."""
import bpy, math, os, sys
from mathutils import Vector, Euler

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import hector_rig as rig
import hector_anims as anims

OUT = sys.argv[sys.argv.index("--") + 1] if "--" in sys.argv else os.path.join(HERE, "Export")
os.makedirs(OUT, exist_ok=True)

bpy.ops.wm.read_factory_settings(use_empty=True)
scene = bpy.context.scene
scene.render.fps = 30
scene.unit_settings.system = 'METRIC'
scene.unit_settings.scale_length = 0.01   # 1 BU = 1 cm, exported 1:1 to UE

arm = rig.build_armature(scene)
body = rig.build_mesh(scene, arm)


def key_pose(p, frame):
    for pb in arm.pose.bones:
        pb.rotation_mode = 'XYZ'
        pb.rotation_euler = Euler([math.radians(a) for a in p.get(pb.name, (0, 0, 0))], 'XYZ')
        pb.keyframe_insert("rotation_euler", frame=frame)
    root = arm.pose.bones["root"]
    root.location = Vector(p.get("root_loc", (0, 0, 0)))
    root.keyframe_insert("location", frame=frame)


def export_fbx(path, anim):
    bpy.ops.object.select_all(action='DESELECT')
    arm.select_set(True)
    body.select_set(True)
    bpy.context.view_layer.objects.active = arm
    bpy.ops.export_scene.fbx(
        filepath=path, use_selection=True, apply_unit_scale=True, apply_scale_options='FBX_SCALE_UNITS',
        axis_forward='-Y', axis_up='Z', object_types={'ARMATURE', 'MESH'}, add_leaf_bones=False,
        armature_nodetype='NULL', mesh_smooth_type='FACE', use_armature_deform_only=False,
        bake_anim=anim, bake_anim_use_all_bones=True, bake_anim_use_nla_strips=False,
        bake_anim_use_all_actions=False, bake_anim_force_startend_keying=True, bake_anim_simplify_factor=0.0)


# --- bind-pose mesh
arm.animation_data_clear()
export_fbx(os.path.join(OUT, "SK_Hector.fbx"), anim=False)

# --- animations
for name, keys in anims.ANIMS.items():
    arm.animation_data_clear()
    arm.animation_data_create().action = bpy.data.actions.new(f"A_Hector_{name}")
    for frame, p in keys:
        key_pose(p, frame)
    scene.frame_start, scene.frame_end = 0, keys[-1][0]
    export_fbx(os.path.join(OUT, f"A_Hector_{name}.fbx"), anim=True)

# --- preview renders (front/side bind pose + mid-frame of key anims) for review
cam_data = bpy.data.cameras.new("Cam")
cam_data.type = 'ORTHO'
cam_data.ortho_scale = 230
cam = bpy.data.objects.new("Cam", cam_data)
scene.collection.objects.link(cam)
scene.camera = cam
sun = bpy.data.objects.new("Sun", bpy.data.lights.new("Sun", 'SUN'))
sun.data.energy = 4.0
sun.rotation_euler = Euler((math.radians(50), 0, math.radians(30)))
scene.collection.objects.link(sun)
world = bpy.data.worlds.new("W")
world.color = (0.25, 0.25, 0.28)
scene.world = world
scene.render.engine = 'BLENDER_EEVEE_NEXT' if 'BLENDER_EEVEE_NEXT' in [e.identifier for e in bpy.types.RenderSettings.bl_rna.properties['engine'].enum_items] else 'BLENDER_EEVEE'
scene.render.resolution_x, scene.render.resolution_y = 512, 640
PREV = os.path.join(OUT, "preview")
os.makedirs(PREV, exist_ok=True)


def shoot(name, frame, view):
    scene.frame_set(frame)
    if view == "front":
        cam.location, cam.rotation_euler = (0, -500, 95), Euler((math.radians(90), 0, 0))
    else:
        cam.location, cam.rotation_euler = (500, 0, 95), Euler((math.radians(90), 0, math.radians(90)))
    scene.render.filepath = os.path.join(PREV, f"{name}_{view}.png")
    bpy.ops.render.render(write_still=True)


arm.animation_data_clear()
shoot("BindPose", 0, "front")
shoot("BindPose", 0, "side")
for name in ("Idle", "Run", "Light3", "Guard", "Heavy"):
    keys = anims.ANIMS[name]
    arm.animation_data_clear()
    arm.animation_data_create().action = bpy.data.actions.new(f"prev_{name}")
    for frame, p in keys:
        key_pose(p, frame)
    shoot(name, keys[len(keys) // 2][0], "front")

m = body.data
print(f"HECTOR_GENERATED verts={len(m.vertices)} faces={len(m.polygons)} bones={len(rig.BONES)} anims={len(anims.ANIMS)} out={OUT}")
