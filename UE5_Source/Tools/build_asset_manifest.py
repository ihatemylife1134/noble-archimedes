def generate_manifest():
    manifest = {
        "format": "UE5 Asset Manifest",
        "version": "1.0",
        "total_assets": 0,
        "categories": {}
    }
    
    for category, info in ASSET_CATEGORIES.items():
        category_info = {
            "path": info["path"],
            "extensions": info["extensions"],
            "item_count": len(info["items"]),
            "items": info["items"],
        }
        manifest["categories"][category] = category_info
        manifest["total_assets"] += len(info["items"])
    
    manifest_file = PROJECT_ROOT / "Content" / "AssetManifest.json"
    manifest_file.parent.mkdir(parents=True, exist_ok=True)
    
    with open(manifest_file, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
    
    print(f"Asset manifest generated: {manifest_file}")
    print(f"Total assets: {manifest['total_assets']}")
    print(f"Categories: {len(ASSET_CATEGORIES)}")
    
    for category, info in ASSET_CATEGORIES.items():
        print(f"  {category}: {len(info['items'])} assets")

if __name__ == "__main__":
    generate_manifest()